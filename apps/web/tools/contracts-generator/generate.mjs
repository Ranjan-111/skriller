import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const schemaFlag = process.argv.indexOf("--schema");
const schemaUrl =
  schemaFlag >= 0
    ? pathToFileURL(process.argv[schemaFlag + 1])
    : new URL("../../contracts/openapi.json", import.meta.url);
const outputUrl = new URL("../../src/generated/api.ts", import.meta.url);
const schema = JSON.parse(await readFile(schemaUrl, "utf8"));
const generated = `/** Generated by openapi-typescript 7.10.1 from contracts/openapi.json. Do not edit. */\n${astToString(await openapiTS(schema))}`;
if (process.argv.includes("--check")) {
  let existing;
  try {
    existing = await readFile(outputUrl, "utf8");
  } catch {
    existing = "";
  }
  if (existing !== generated) {
    console.error(
      "Generated client types differ from API schema; run contracts:generate.",
    );
    process.exitCode = 1;
  }
} else {
  await writeFile(outputUrl, generated);
  console.log(`Generated ${fileURLToPath(outputUrl)}`);
}
